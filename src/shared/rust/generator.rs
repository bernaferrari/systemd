/// Mirrors C `generator_write_veritysetup_service_section()`.
pub fn format_veritysetup_service_section(
    name: &str,
    data_what: &str,
    hash_what: &str,
    roothash: Option<&str>,
    options: Option<&str>,
) -> String {
    let name_e = specifier_escape(name);
    let data_e = specifier_escape(data_what);
    let hash_e = specifier_escape(hash_what);
    let root_e = roothash.map(|r| specifier_escape(r));
    let opts_e = options.map(|o| specifier_escape(o));

    format!(
        "\n\
         [Service]\n\
         Type=oneshot\n\
         RemainAfterExit=yes\n\
         ExecStart=systemd-veritysetup attach '{name_e}' '{data_e}' '{hash_e}' '{}' '{}'\n\
         ExecStop=systemd-veritysetup detach '{name_e}'\n",
        empty_to_dash(root_e.as_deref()),
        strempty(opts_e.as_deref()),
    )
}

