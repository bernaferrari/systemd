// ── Error type ──────────────────────────────────────────────────────────

/// Errors returned by generator utility functions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GeneratorError {
    /// A required argument was empty or missing.
    InvalidArgument,
    /// Expected a regular file path but received a directory path.
    IsDirectory,
    /// The requested operation is not supported.
    NotSupported,
}

impl fmt::Display for GeneratorError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidArgument => write!(f, "invalid argument"),
            Self::IsDirectory => write!(f, "path refers to a directory, not a file"),
            Self::NotSupported => write!(f, "operation not supported"),
        }
    }
}

impl std::error::Error for GeneratorError {}

// ── Enums ───────────────────────────────────────────────────────────────

/// GPT auto-root partition detection mode.
///
/// Controls how partition auto-detection is configured via the kernel
/// command line `root=` parameter.  Mirrors the C `GptAutoRoot` enum.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GptAutoRoot {
    /// Auto-detection disabled (default / unknown values).
    Off,
    /// Auto-detection enabled, respecting factory-reset mode.
    On,
    /// Auto-detection forced, ignoring factory-reset mode.
    Force,
    /// Full-image dissection, respecting factory-reset mode.
    Dissect,
    /// Full-image dissection forced, ignoring factory-reset mode.
    DissectForce,
}

// ── Private helpers ─────────────────────────────────────────────────────

fn specifier_escape(s: &str) -> String {
    s.replace('%', "%%")
}

fn cescape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\x00"),
            c if c.is_control() => {
                out.push_str(&format!("\\x{:02x}", ch as u32));
            }
            c => out.push(c),
        }
    }
    out
}

// Mirrors systemd's `empty_to_dash`.
fn empty_to_dash(s: Option<&str>) -> &str {
    match s {
        Some(v) if !v.is_empty() => v,
        _ => "-",
    }
}

// Mirrors systemd's `strempty`.
fn strempty<'a>(s: Option<&'a str>) -> &'a str {
    s.unwrap_or("")
}

// Mirrors `unit_name_path_escape` for the common generator cases.
fn unit_name_path_escape(path: &str) -> String {
    let trimmed = path.trim_matches('/');
    if trimmed.is_empty() {
        return String::new();
    }
    let mut result = String::with_capacity(trimmed.len());
    for ch in trimmed.chars() {
        match ch {
            '/' => result.push('-'),
            '\\' => result.push_str("\\x5c"),
            '\0'..='\x1f' => result.push_str(&format!("\\x{:02x}", ch as u32)),
            _ => result.push(ch),
        }
    }
    result.trim_matches('-').to_string()
}

// ── Public API ──────────────────────────────────────────────────────────

/// Generate the standard auto-generated header comment for unit files.
///
/// # Examples
///
/// ```
/// assert!(generator_header("systemd-fstab-generator").starts_with("# Automatically generated by"));
/// ```
pub fn generator_header(program: &str) -> String {
    format!("# Automatically generated by {program}\n\n")
}

/// Parse the GPT auto-root detection mode from a kernel command line value.
///
/// Mirrors the C `parse_gpt_auto_root()`.  Returns [`GptAutoRoot::Off`]
/// for the value `"off"` and for any unrecognised value.
///
/// # Panics
///
/// Panics if `switch_name` or `value` is empty.
pub fn parse_gpt_auto_root(switch_name: &str, value: &str) -> GptAutoRoot {
    assert!(!switch_name.is_empty(), "switch_name must not be empty");
    assert!(!value.is_empty(), "value must not be empty");

    match value {
        "gpt-auto" => GptAutoRoot::On,
        "gpt-auto-force" => GptAutoRoot::Force,
        "dissect" => GptAutoRoot::Dissect,
        "dissect-force" => GptAutoRoot::DissectForce,
        _ => GptAutoRoot::Off,
    }
}

/// Parse the `SYSTEMD_SOFT_REBOOTS_COUNT` value and return whether the
/// system has been soft-rebooted (count > 0).
///
/// This is the pure-logic core extracted from [`generator_soft_rebooted`]
/// so it can be tested without touching the process environment.
pub fn soft_rebooted_from_value(raw: Option<&str>) -> bool {
    raw.and_then(|v| v.parse::<u32>().ok())
        .map(|n| n > 0)
        .unwrap_or(false)
}

/// Check whether the system has been soft-rebooted.
///
/// Reads `SYSTEMD_SOFT_REBOOTS_COUNT` from the environment and returns
/// `true` when the value is present and greater than zero.
/// The result is cached for the process lifetime.
pub fn generator_soft_rebooted() -> bool {
    static CACHE: OnceLock<bool> = OnceLock::new();
    *CACHE.get_or_init(|| {
        soft_rebooted_from_value(std::env::var("SYSTEMD_SOFT_REBOOTS_COUNT").ok().as_deref())
    })
}

/// Compute the `(from, to)` paths for a generator dependency symlink.
///
/// * `dep_type` = `Some("wants")`  → creates a `<dst>.wants/<src>` dependency
/// * `dep_type` = `None`           → creates an alias symlink to `<src>`
/// * `instance` = `Some("sda1")`   → instantiate template `<src>` → `<src>@sda1.<suffix>`
///
/// # Errors
///
/// Returns [`GeneratorError::InvalidArgument`] if `dir`, `dst`, or `src` is empty.
/// Returns [`GeneratorError::IsDirectory`] if `src` ends with `/`.
pub fn generator_add_symlink_path(
    dir: &str,
    dst: &str,
    dep_type: Option<&str>,
    src: &str,
    instance: Option<&str>,
) -> Result<(String, String), GeneratorError> {
    if dir.is_empty() || dst.is_empty() || src.is_empty() {
        return Err(GeneratorError::InvalidArgument);
    }

    let (dir_prefix, filename) = match src.rfind('/') {
        Some(pos) => {
            let f = &src[pos + 1..];
            if f.is_empty() {
                return Err(GeneratorError::IsDirectory);
            }
            (&src[..pos], f)
        }
        None => ("", src),
    };

    let resolved_name = match instance {
        Some(inst) => {
            if let Some(at_pos) = filename.find("@.") {
                let prefix = &filename[..=at_pos];
                let suffix = &filename[at_pos + 2..];
                format!("{prefix}{inst}.{suffix}")
            } else {
                filename.to_string()
            }
        }
        None => filename.to_string(),
    };

    let from = match dep_type {
        Some(_) if dir_prefix.is_empty() => format!("../{resolved_name}"),
        Some(_) => format!("{dir_prefix}/{resolved_name}"),
        None if dir_prefix.is_empty() => resolved_name.clone(),
        None => format!("{dir_prefix}/{resolved_name}"),
    };

    let to = match dep_type {
        Some(dep) => format!("{dir}/{dst}.{dep}/{resolved_name}"),
        None => format!("{dir}/{dst}"),
    };

    Ok((from, to))
}

/// Mirrors C `generator_add_ordering`.
pub fn generator_ordering_dropin_filename(src: &str, dst: &str) -> String {
    format!("{src}.d/50-order-{dst}.conf")
}

/// Mirrors C `generator_add_ordering`.
pub fn generator_ordering_dropin_content(order: &str, dst: &str, program: &str) -> String {
    format!("{}[Unit]\n{order}={dst}\n", generator_header(program))
}

/// Mirrors C `generator_write_blockdev_dependency`.
pub fn format_blockdev_dependency(what: &str) -> Option<String> {
    if !what.starts_with("/dev/") {
        return None;
    }
    let escaped = unit_name_path_escape(what);
    Some(format!("After=blockdev@{escaped}.target\n"))
}

/// Mirrors C `generator_write_cryptsetup_unit_section()`.
pub fn format_cryptsetup_unit_section(source: Option<&str>) -> String {
    let mut s = String::from(
        "[Unit]\n\
         Description=Cryptography Setup for %I\n\
         Documentation=man:crypttab(5) man:systemd-cryptsetup-generator(8) \
         man:systemd-cryptsetup@.service(8)\n",
    );
    if let Some(src) = source {
        s.push_str(&format!("SourcePath={src}\n"));
    }
    s.push_str(
        "\n\
         DefaultDependencies=no\n\
         After=cryptsetup-pre.target systemd-udevd-kernel.socket \
         systemd-tpm2-setup-early.service\n\
         Before=blockdev@dev-mapper-%i.target\n\
         Wants=blockdev@dev-mapper-%i.target\n\
         IgnoreOnIsolate=true\n",
    );
    s
}

/// Mirrors C `generator_write_cryptsetup_service_section()`.
pub fn format_cryptsetup_service_section(
    name: &str,
    what: &str,
    key_file: Option<&str>,
    options: Option<&str>,
) -> String {
    let name_e = specifier_escape(name);
    let what_e = specifier_escape(what);
    let key_e = key_file.map(|k| specifier_escape(k));
    let opts_e = options.map(|o| specifier_escape(o));

    format!(
        "\n\
         [Service]\n\
         Type=oneshot\n\
         RemainAfterExit=yes\n\
         TimeoutSec=infinity\n\
         KeyringMode=shared\n\
         OOMScoreAdjust=500\n\
         ImportCredential=cryptsetup.*\n\
         ExecStart=systemd-cryptsetup attach '{name_e}' '{what_e}' '{}' '{}'\n\
         ExecStop=systemd-cryptsetup detach '{name_e}'\n",
        strempty(key_e.as_deref()),
        strempty(opts_e.as_deref()),
    )
}

